"""eta_mlflow.py -- Part B: MLflow registry, multi-criteria promotion gate.

Usage (from the project root, with data/ generated by eta_data.py):
    export MLFLOW_TRACKING_URI=sqlite:///mlflow.db        # default if unset
    python partB/eta_mlflow.py register
    python partB/eta_mlflow.py gate                       # default thresholds
    python partB/eta_mlflow.py gate --min-rel-gain 0.60

IMPORTANT: run `register` as a script (python eta_mlflow.py register), not via `import`.
Then the pyfunc class is pickled by value (module __main__) and `mlflow models serve`
does not need this file or eta_data on its path.
"""
import argparse
import json
import os
import sys
import time

import joblib
import numpy as np
import pandas as pd

HERE = os.path.dirname(os.path.abspath(__file__))
for _p in (HERE, os.path.dirname(HERE)):
    if _p not in sys.path:
        sys.path.insert(0, _p)

import mlflow
import mlflow.pyfunc
import eta_data
from mlflow.models import infer_signature
from mlflow.tracking import MlflowClient

MODEL_NAME = "eta-model"
FEATURES = eta_data.FEATURES
RUSH_HOURS = [7, 8, 9, 16, 17, 18, 19]


def _tracking_uri():
    return os.environ.get("MLFLOW_TRACKING_URI", "sqlite:///mlflow.db")


def _data_path(name):
    for base in (os.getcwd(), HERE, os.path.dirname(HERE)):
        p = os.path.join(base, "data", name)
        if os.path.exists(p):
            return p
    raise FileNotFoundError(f"data/{name} not found -- run `python eta_data.py` first")


# ----------------------------------------------------------------------------- B1 pyfunc
class EtaPyfunc(mlflow.pyfunc.PythonModel):
    """Wraps a {model, feature_columns, version} bundle.
    Returns a DataFrame with columns eta_minutes (1 decimal) and model_version."""

    def load_context(self, context):
        b = joblib.load(context.artifacts["bundle"])
        self.model, self.cols, self.version = b["model"], list(b["feature_columns"]), b["version"]

    def predict(self, context, model_input, params=None):
        X = pd.DataFrame(model_input)[self.cols]
        preds = np.round(self.model.predict(X), 1).astype(float)
        return pd.DataFrame({"eta_minutes": preds, "model_version": self.version})


def register():
    """Log v1 and v2 (signature, input example, pinned pip reqs) and register as eta-model
    with aliases prod -> v1, candidate -> v2. Prints the registry table."""
    import sklearn
    mlflow.set_tracking_uri(_tracking_uri())
    mlflow.set_experiment("eta")
    client = MlflowClient()

    example = eta_data.make_data(2000, seed=99)[FEATURES].head(5).astype("float64")
    reqs = [f"mlflow=={mlflow.__version__}", f"scikit-learn=={sklearn.__version__}",
            f"pandas=={pd.__version__}", f"numpy=={np.__version__}",
            f"joblib=={joblib.__version__}", "cloudpickle"]

    versions = {}
    for v in ("v1", "v2"):
        path = _data_path(f"eta_{v}.joblib")
        b = joblib.load(path)
        out = pd.DataFrame({"eta_minutes": np.round(b["model"].predict(example[b["feature_columns"]]), 1).astype(float),
                            "model_version": v})
        sig = infer_signature(example, out)
        with mlflow.start_run(run_name=f"eta-{v}"):
            mlflow.log_param("bundle_version", v)
            mlflow.log_param("estimator", type(b["model"]).__name__)
            info = mlflow.pyfunc.log_model(
                name="model", python_model=EtaPyfunc(), artifacts={"bundle": path},
                signature=sig, input_example=example, pip_requirements=reqs,
                registered_model_name=MODEL_NAME)
        versions[v] = str(info.registered_model_version)

    client.set_registered_model_alias(MODEL_NAME, "prod", versions["v1"])
    client.set_registered_model_alias(MODEL_NAME, "candidate", versions["v2"])

    print(f"{'version':<8}{'bundle':<8}{'aliases'}")
    for mv in sorted(client.search_model_versions(f"name='{MODEL_NAME}'"), key=lambda m: int(m.version)):
        bundle = {v: k for k, v in versions.items()}.get(str(mv.version), "-")
        print(f"{mv.version:<8}{bundle:<8}{sorted(mv.aliases)}")
    return versions


# ----------------------------------------------------------------------------- B2 gate
def decide(prod, cand, min_rel_gain=0.03, max_p95_ms=10.0, max_slice_regression=0.05):
    """Pure function. prod/cand: dicts with mae, mae_rush, mae_rain, p95_ms.
    Slice regression is RELATIVE: cand_slice_mae <= prod_slice_mae * (1 + max_slice_regression)."""
    criteria = {
        "overall_gain": cand["mae"] <= prod["mae"] * (1 - min_rel_gain),
        "latency": cand["p95_ms"] <= max_p95_ms,
        "rush_slice": cand["mae_rush"] <= prod["mae_rush"] * (1 + max_slice_regression),
        "rain_slice": cand["mae_rain"] <= prod["mae_rain"] * (1 + max_slice_regression),
    }
    return {"criteria": criteria, "promote": all(criteria.values())}


def _metrics(m, fresh):
    X = fresh[FEATURES].astype("float64")
    y = fresh["eta_minutes"].to_numpy()
    err = np.abs(m.predict(X)["eta_minutes"].to_numpy() - y)
    rush = fresh["hour"].isin(RUSH_HOURS).to_numpy()
    rain = (fresh["rain"] == 1).to_numpy()
    times = []
    for i in range(205):
        t0 = time.perf_counter()
        m.predict(X.iloc[[i]])
        times.append((time.perf_counter() - t0) * 1000)
    return {"mae": float(err.mean()), "mae_rush": float(err[rush].mean()),
            "mae_rain": float(err[rain].mean()), "p95_ms": float(np.percentile(times[5:], 95))}


def promotion_gate(**thresholds):
    mlflow.set_tracking_uri(_tracking_uri())
    prod = mlflow.pyfunc.load_model(f"models:/{MODEL_NAME}@prod")
    cand = mlflow.pyfunc.load_model(f"models:/{MODEL_NAME}@candidate")
    fresh = eta_data.make_data(2000, seed=99)
    mp, mc = _metrics(prod, fresh), _metrics(cand, fresh)
    result = decide(mp, mc, **thresholds)
    print("thresholds:", thresholds or "defaults")
    print("prod     :", {k: round(v, 3) for k, v in mp.items()})
    print("candidate:", {k: round(v, 3) for k, v in mc.items()})
    print("rel. MAE gain: %.1f%%" % (100 * (mp["mae"] - mc["mae"]) / mp["mae"]))
    print(json.dumps(result, indent=2))
    return result


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("cmd", choices=["register", "gate"])
    ap.add_argument("--min-rel-gain", type=float)
    ap.add_argument("--max-p95-ms", type=float)
    ap.add_argument("--max-slice-regression", type=float)
    a = ap.parse_args()
    if a.cmd == "register":
        register()
    else:
        th = {k: v for k, v in dict(min_rel_gain=a.min_rel_gain, max_p95_ms=a.max_p95_ms,
                                    max_slice_regression=a.max_slice_regression).items() if v is not None}
        promotion_gate(**th)
